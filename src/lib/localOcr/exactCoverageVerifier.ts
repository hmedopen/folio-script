/**
 * Folio Script — Exact Spatial Union Coverage Verifier
 * Calculates the exact mathematical 2D difference between the page boundary
 * and the spatial union of all successfully processed tiles.
 * Declares complete if and only if unprocessed area is mathematically zero.
 */

import type { TileTransformRecord } from '../../types/localOcr.ts';

export interface UnprocessedGap {
  ymin: number;
  xmin: number;
  ymax: number;
  xmax: number;
  area: number;
}

export interface ExactCoverageReport {
  isFullyCovered: boolean;
  coverageRatio: number; // 0.0 to 1.0
  unprocessedAreaPixels: number;
  unprocessedGaps: UnprocessedGap[];
  plannedTileCount: number;
  succeededTileCount: number;
  failedTileCount: number;
  status: 'complete' | 'partial' | 'failed';
}

/**
 * Merges adjacent uncovered rectangular cells horizontally and vertically
 * to produce a clean, non-overlapping list of bounding gap boxes.
 */
function mergeContiguousGapBoxes(rawGaps: UnprocessedGap[]): UnprocessedGap[] {
  if (rawGaps.length <= 1) return rawGaps;

  // 1. Group by ymin and ymax, merge horizontally contiguous cells
  const sorted = [...rawGaps].sort((a, b) => a.ymin - b.ymin || a.xmin - b.xmin);
  const horizontallyMerged: UnprocessedGap[] = [];

  for (const gap of sorted) {
    const last = horizontallyMerged[horizontallyMerged.length - 1];
    if (
      last &&
      last.ymin === gap.ymin &&
      last.ymax === gap.ymax &&
      Math.abs(last.xmax - gap.xmin) < 1e-4
    ) {
      last.xmax = gap.xmax;
      last.area = (last.xmax - last.xmin) * (last.ymax - last.ymin);
    } else {
      horizontallyMerged.push({ ...gap });
    }
  }

  // 2. Group by xmin and xmax, merge vertically contiguous cells
  const verticallyMerged: UnprocessedGap[] = [];
  const sortedV = [...horizontallyMerged].sort((a, b) => a.xmin - b.xmin || a.ymin - b.ymin);

  for (const gap of sortedV) {
    const last = verticallyMerged[verticallyMerged.length - 1];
    if (
      last &&
      last.xmin === gap.xmin &&
      last.xmax === gap.xmax &&
      Math.abs(last.ymax - gap.ymin) < 1e-4
    ) {
      last.ymax = gap.ymax;
      last.area = (last.xmax - last.xmin) * (last.ymax - last.ymin);
    } else {
      verticallyMerged.push({ ...gap });
    }
  }

  return verticallyMerged;
}

/**
 * Computes exact spatial coverage of a page by integrating over elementary grid cells
 * generated by the boundaries of successfully processed tiles.
 */
export function computeExactCoverage(
  pageWidth: number,
  pageHeight: number,
  allTiles: TileTransformRecord[],
  succeededTileIds: Set<string> | string[]
): ExactCoverageReport {
  const succeededIdSet = succeededTileIds instanceof Set ? succeededTileIds : new Set(succeededTileIds);
  const succeededTiles = allTiles.filter((t) => succeededIdSet.has(t.tileId));
  const failedTiles = allTiles.filter((t) => !succeededIdSet.has(t.tileId));

  const totalPageArea = pageWidth * pageHeight;
  if (totalPageArea <= 0) {
    throw new Error(`Invalid page dimensions for coverage verification: ${pageWidth}x${pageHeight}`);
  }

  if (succeededTiles.length === 0) {
    return {
      isFullyCovered: false,
      coverageRatio: 0.0,
      unprocessedAreaPixels: totalPageArea,
      unprocessedGaps: [
        {
          ymin: 0,
          xmin: 0,
          ymax: pageHeight,
          xmax: pageWidth,
          area: totalPageArea,
        },
      ],
      plannedTileCount: allTiles.length,
      succeededTileCount: 0,
      failedTileCount: allTiles.length,
      status: 'failed',
    };
  }

  // 1. Collect all unique x and y boundary points
  const xSet = new Set<number>([0, pageWidth]);
  const ySet = new Set<number>([0, pageHeight]);

  for (const t of succeededTiles) {
    const x1 = Math.max(0, Math.min(pageWidth, t.originX));
    const x2 = Math.max(0, Math.min(pageWidth, t.originX + t.cropWidth));
    const y1 = Math.max(0, Math.min(pageHeight, t.originY));
    const y2 = Math.max(0, Math.min(pageHeight, t.originY + t.cropHeight));
    xSet.add(x1);
    xSet.add(x2);
    ySet.add(y1);
    ySet.add(y2);
  }

  const xPoints = Array.from(xSet).sort((a, b) => a - b);
  const yPoints = Array.from(ySet).sort((a, b) => a - b);

  let coveredArea = 0;
  const rawGaps: UnprocessedGap[] = [];

  // 2. Exact elementary grid cell integration
  for (let j = 0; j < yPoints.length - 1; j++) {
    const y1 = yPoints[j];
    const y2 = yPoints[j + 1];
    const cellH = y2 - y1;
    if (cellH <= 0) continue;
    const midY = (y1 + y2) / 2;

    for (let i = 0; i < xPoints.length - 1; i++) {
      const x1 = xPoints[i];
      const x2 = xPoints[i + 1];
      const cellW = x2 - x1;
      if (cellW <= 0) continue;
      const midX = (x1 + x2) / 2;

      // Point-in-rectangle test: is midpoint covered by ANY succeeded tile?
      let covered = false;
      for (const t of succeededTiles) {
        if (
          midX >= t.originX &&
          midX < t.originX + t.cropWidth &&
          midY >= t.originY &&
          midY < t.originY + t.cropHeight
        ) {
          covered = true;
          break;
        }
      }

      const cellArea = cellW * cellH;
      if (covered) {
        coveredArea += cellArea;
      } else {
        rawGaps.push({
          ymin: y1,
          xmin: x1,
          ymax: y2,
          xmax: x2,
          area: cellArea,
        });
      }
    }
  }

  const mergedGaps = mergeContiguousGapBoxes(rawGaps);
  const unprocessedAreaPixels = totalPageArea - coveredArea;
  const coverageRatio = Math.max(0, Math.min(1.0, coveredArea / totalPageArea));
  const isFullyCovered = mergedGaps.length === 0 && Math.abs(coverageRatio - 1.0) < 1e-6;

  return {
    isFullyCovered,
    coverageRatio: Math.round(coverageRatio * 10000) / 10000,
    unprocessedAreaPixels: Math.round(unprocessedAreaPixels * 10) / 10,
    unprocessedGaps: mergedGaps,
    plannedTileCount: allTiles.length,
    succeededTileCount: succeededTiles.length,
    failedTileCount: failedTiles.length,
    status: isFullyCovered ? 'complete' : 'partial',
  };
}
